axes[0, 0].set_ylim(0, 1.1)

# 2. ROC curve comparison
for res in results:
    fpr, tpr, _ = roc_curve(y_test, res["y_proba"])
    axes[0, 1].plot(fpr, tpr, label=f"{res['Model name']} (AUC = {res['ROC-AUC']:.3f})")
